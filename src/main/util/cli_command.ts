/**
 * `cogseed` 命令行入口的生成与安装。
 *
 * 目标：让用户在终端直接敲 `cogseed …`，**不需要系统 Node**——用应用自带的
 * Electron 运行时以 Node 模式（`ELECTRON_RUN_AS_NODE=1`）执行 `bin/cogseed-pkg.cjs`。
 * 这也是仓库此前缺的一块：`package.json` 没有 `bin` 暴露，安装器脚本一个都没有
 * （Windows 真机核对：`bin/*.ps1|*.cmd|*.sh` 为空）。
 *
 * 设计约束：
 * - **幂等**：重复安装结果一致；只在内容变化时重写。
 * - **不覆盖别人的文件**：目标已存在且不含我们的标记时拒绝，交由用户处理。
 * - **卸载只删自己写的**：认标记，不按文件名乱删。
 * - 安装位置选 PATH 上的用户级目录（macOS `~/.local/bin`，Windows `%LOCALAPPDATA%\CogSeed\bin`），
 *   不碰 `/usr/local/bin` 这类需要提权的位置。
 * - 平台分支全部可注入（`platform` / `env`），因此 Windows 内容能在 macOS 上被夹具钉住。
 */

import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

/** 与脚本同名的默认命令。 */
export const CLI_COMMAND_NAME = 'cogseed';
/** 标记行：用于"只覆盖/只删除自己写的文件"。 */
export const CLI_SHIM_MARKER = 'cogseed-cli-shim v1';

export type CliPlatform = 'darwin' | 'linux' | 'win32' | string;

export interface CliShimSpec {
  platform: CliPlatform;
  /** 应用根：dev 为仓库根，打包态为 app.asar。 */
  appRoot: string;
  /** Electron 可执行文件（以 Node 模式运行）。 */
  runtimeBin: string;
  /** 数据根；省略表示由 CLI 自行解析。 */
  workspaceRoot?: string;
  /** 活跃 uid；省略则交由 CLI 从容器注册表解析。 */
  uid?: string;
}

function quoteSh(value: string): string {
  return `"${String(value).replace(/(["\\$`])/g, '\\$1')}"`;
}

function quoteCmd(value: string): string {
  // cmd 里引号内不需要转义反斜杠；`%` 必须写成 `%%` 以免被当作变量展开。
  return `"${String(value).replace(/%/g, '%%')}"`;
}

/** `set "NAME=value"` 里的值同样要转义 `%`（否则 `C:\100%\…` 会被 cmd 吃掉）。 */
function cmdValue(value: string): string {
  return String(value).replace(/"/g, '').replace(/%/g, '%%');
}

/** 生成 shim 文本（macOS/Linux 为 sh，Windows 为 cmd）。 */
export function buildCliShim(spec: CliShimSpec): string {
  const { platform, appRoot, runtimeBin, workspaceRoot, uid } = spec;
  if (platform === 'win32') {
    const entries = path.win32.join(appRoot, 'bin', 'cogseed-pkg.cjs');
    const lines = [
      '@echo off',
      `REM ${CLI_SHIM_MARKER} (generated by CogSeed; safe to delete)`,
      'setlocal',
      'set "ELECTRON_RUN_AS_NODE=1"',
      `set "COGSEED_PC_DIR=${cmdValue(appRoot)}"`,
    ];
    if (workspaceRoot) lines.push(`set "COGSEED_WORKSPACE_ROOT=${cmdValue(workspaceRoot)}"`);
    if (uid) lines.push(`set "COGSEED_UID=${cmdValue(uid)}"`);
    lines.push(`${quoteCmd(runtimeBin)} ${quoteCmd(entries)} %*`, '');
    return lines.join('\r\n');
  }
  const entries = path.posix.join(appRoot, 'bin', 'cogseed-pkg.cjs');
  const env: string[] = ['ELECTRON_RUN_AS_NODE=1', `COGSEED_PC_DIR=${quoteSh(appRoot)}`];
  if (workspaceRoot) env.push(`COGSEED_WORKSPACE_ROOT=${quoteSh(workspaceRoot)}`);
  if (uid) env.push(`COGSEED_UID=${quoteSh(uid)}`);
  return [
    '#!/bin/sh',
    `# ${CLI_SHIM_MARKER} (generated by CogSeed; safe to delete)`,
    `exec env ${env.join(' ')} ${quoteSh(runtimeBin)} ${quoteSh(entries)} "$@"`,
    '',
  ].join('\n');
}

/** shim 文件名（Windows 需要扩展名才能被 PATHEXT 解析到）。 */
export function cliShimFileName(commandName: string, platform: CliPlatform): string {
  return platform === 'win32' ? `${commandName}.cmd` : commandName;
}

/** 用户级安装目录：PATH 上通常已有，且不需要提权。 */
export function defaultCliInstallDir(platform: CliPlatform, env: NodeJS.ProcessEnv = process.env): string {
  if (platform === 'win32') {
    const base = env.LOCALAPPDATA || env.APPDATA || os.homedir();
    return path.win32.join(base, 'CogSeed', 'bin');
  }
  const home = env.HOME || os.homedir();
  const xdg = env.XDG_BIN_HOME;
  if (xdg) return xdg;
  // 必须用 posix 拼接：这个分支会在 Windows 主机上被单测/打包逻辑以 'darwin' 调用，
  // 用宿主 `path.join` 会得到 `\Users\me\.local\bin`（真机验收抓到的实现缺陷）。
  return path.posix.join(home, '.local', 'bin');
}

export interface CliInstallResult {
  path: string;
  /** false = 内容一致，未重写。 */
  changed: boolean;
}

export class CliShimConflictError extends Error {
  constructor(readonly target: string) {
    super(`refusing to overwrite a file CogSeed did not write: ${target}`);
    this.name = 'CliShimConflictError';
  }
}

function isOurShim(file: string): boolean {
  try {
    return fs.readFileSync(file, 'utf8').slice(0, 4096).includes(CLI_SHIM_MARKER);
  } catch {
    return false;
  }
}

/** 安装（或更新）命令。目标存在但不是我们的文件时抛 `CliShimConflictError`。 */
export function installCliCommand(
  spec: CliShimSpec & { dir: string; commandName?: string },
): CliInstallResult {
  const name = spec.commandName || CLI_COMMAND_NAME;
  const file = path.join(spec.dir, cliShimFileName(name, spec.platform));
  const content = buildCliShim(spec);
  fs.mkdirSync(spec.dir, { recursive: true });
  if (fs.existsSync(file)) {
    if (!isOurShim(file)) throw new CliShimConflictError(file);
    if (fs.readFileSync(file, 'utf8') === content) return { path: file, changed: false };
  }
  fs.writeFileSync(file, content, 'utf8');
  if (spec.platform !== 'win32') fs.chmodSync(file, 0o755);
  return { path: file, changed: true };
}

/** 卸载：只删带标记的那个文件。 */
export function uninstallCliCommand(options: {
  dir: string;
  platform: CliPlatform;
  commandName?: string;
}): { removed: string[] } {
  const name = options.commandName || CLI_COMMAND_NAME;
  const file = path.join(options.dir, cliShimFileName(name, options.platform));
  if (!fs.existsSync(file) || !isOurShim(file)) return { removed: [] };
  fs.rmSync(file);
  return { removed: [file] };
}

export interface CliStatus {
  installed: boolean;
  path: string;
  /** 已安装但内容与当前期望不一致（例如应用被移动过）→ 建议重装。 */
  stale: boolean;
  /** 目标存在且不是我们的文件。 */
  conflict: boolean;
}

export function cliCommandStatus(
  spec: CliShimSpec & { dir: string; commandName?: string },
): CliStatus {
  const name = spec.commandName || CLI_COMMAND_NAME;
  const file = path.join(spec.dir, cliShimFileName(name, spec.platform));
  if (!fs.existsSync(file)) return { installed: false, path: file, stale: false, conflict: false };
  if (!isOurShim(file)) return { installed: false, path: file, stale: false, conflict: true };
  return {
    installed: true,
    path: file,
    stale: fs.readFileSync(file, 'utf8') !== buildCliShim(spec),
    conflict: false,
  };
}

/** 目录是否已在 PATH 上（安装后给用户的提示用）。 */
export function isDirOnPath(dir: string, env: NodeJS.ProcessEnv = process.env, platform: CliPlatform = process.platform): boolean {
  const delimiter = platform === 'win32' ? ';' : ':';
  const raw = platform === 'win32' ? env.PATH || env.Path || '' : env.PATH || '';
  const normalize = (value: string) => (platform === 'win32' ? value.replace(/[\\/]+$/, '').toLowerCase() : value.replace(/\/+$/, ''));
  const target = normalize(dir);
  return raw.split(delimiter).filter(Boolean).some((entry) => normalize(entry) === target);
}
